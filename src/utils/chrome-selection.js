/**
 * Chrome selection: product phrase + current secondary-nav tab.
 *
 * Two algorithms live here on purpose. Do not unify them.
 *
 * SSR (getActiveSecondaryNavId / isCurrentPage) uses the sidebar id +
 * mapping table. The browser rematch (matchCurrentByHrefPrefix) uses
 * longest href prefix. Paths such as /cookbooks stay null in SSR and
 * current in the client.
 *
 * This module must not import sidebar.config — the client rematch is
 * bundled from SecondaryNav and must not pull the sidebar tree.
 */

import { isHashOnly, normalizePath } from './path-matching.ts'
import { SELF_HOSTED_COLD_DEFAULT_PRODUCT, isDocsProduct } from '../configs/self-hosted.ts'

export {
  PRODUCT_STORAGE_KEY,
  SELF_HOSTED_COLD_DEFAULT_PRODUCT,
  isDocsProduct,
} from '../configs/self-hosted.ts'

/**
 * Self-hosted deployment docs are shared by both products. Header and secondary
 * nav keep the visitor's product (AgentKit or Auth for SaaS) — never a third
 * "Self Hosted" product option.
 */
export function isSelfHostedPath(pathname) {
  return pathname.startsWith('/self-hosted/')
}

/**
 * Determines which product is active based on the current page context.
 * Frontmatter topic and path take precedence; shared self-hosted routes use
 * ?product= then a cold default (sessionStorage is applied client-side only).
 */
export function getActiveProduct(pathname, topic, searchParams) {
  const productParam = searchParams?.get('product')
  if (isDocsProduct(productParam)) return productParam

  if (topic === 'connect') return 'agentkit'
  if (pathname.startsWith('/agentkit/')) return 'agentkit'

  // Shared self-hosted docs: server-side cold default is AgentKit. Client restores
  // SaaS from sessionStorage when the visitor arrived from Auth for SaaS.
  if (isSelfHostedPath(pathname)) return SELF_HOSTED_COLD_DEFAULT_PRODUCT

  return 'saaskit'
}

/**
 * Recursively extracts all paths from sidebar items and maps them to a sidebar ID.
 * Handles string paths, object paths with links, and nested items.
 */
function extractPathsFromItems(items, sidebarId, map) {
  for (const item of items) {
    if (typeof item === 'string') {
      // String items are relative paths like 'authenticate/fsa/quickstart'
      const normalizedPath = normalizePath('/' + item)
      map.set(normalizedPath, sidebarId)
    } else if (item && typeof item === 'object') {
      // Object items may have a link property
      if (item.link && !item.link.startsWith('#')) {
        const normalizedPath = normalizePath(item.link)
        map.set(normalizedPath, sidebarId)
      }
      // Recursively process nested items
      if (item.items && Array.isArray(item.items)) {
        extractPathsFromItems(item.items, sidebarId, map)
      }
      // Handle autogenerate directories by storing the directory prefix
      if (item.autogenerate?.directory) {
        const dirPath = normalizePath('/' + item.autogenerate.directory)
        // Store with a special marker to indicate it's a prefix match
        map.set(`${dirPath}/*`, sidebarId)
      }
    }
  }
}

/**
 * Builds a Map of normalized paths to sidebar IDs from the sidebar configuration.
 * Used only by SSR tab selection.
 */
export function buildPathToSidebarMap(sidebarConfig) {
  const map = new Map()

  for (const sidebar of sidebarConfig) {
    if (sidebar.id && sidebar.items) {
      // Include the sidebar's own entry-point link so paths that match it
      // (but aren't listed in items) still resolve to the correct sidebar
      if (sidebar.link && !sidebar.link.startsWith('#')) {
        map.set(normalizePath(sidebar.link), sidebar.id)
      }
      extractPathsFromItems(sidebar.items, sidebar.id, map)
    }
  }

  return map
}

/**
 * Looks up which sidebar a path belongs to using the path-to-sidebar map.
 * Handles both exact matches and prefix matches for autogenerated directories.
 */
export function getSidebarIdForPath(pathname, pathToSidebarMap) {
  const normalizedPath = normalizePath(pathname)

  // First try exact match
  if (pathToSidebarMap.has(normalizedPath)) {
    return pathToSidebarMap.get(normalizedPath) || null
  }

  // Then try prefix matches for autogenerated directories
  for (const [pattern, sidebarId] of pathToSidebarMap.entries()) {
    if (pattern.endsWith('/*')) {
      const prefix = pattern.slice(0, -2) // Remove '/*'
      if (normalizedPath.startsWith(prefix + '/') || normalizedPath === prefix) {
        return sidebarId
      }
    }
  }

  return null
}

/**
 * Resolves a SecondaryNavMapping to an actual nav item ID.
 * Handles both simple string mappings and complex path-override mappings.
 */
export function resolveNavMapping(mapping, pathname) {
  if (typeof mapping === 'string') {
    return mapping
  }

  // Check path overrides for more specific matches
  if (mapping.pathOverrides) {
    const normalizedPath = normalizePath(pathname)
    for (const [prefix, navId] of Object.entries(mapping.pathOverrides)) {
      const normalizedPrefix = normalizePath(prefix)
      if (
        normalizedPath.startsWith(normalizedPrefix + '/') ||
        normalizedPath === normalizedPrefix
      ) {
        return navId
      }
    }
  }

  return mapping.default || null
}

/**
 * SSR tab id from the sidebar table.
 *
 * Pass the live path map + sidebarToSecondaryNav from the binder
 * (secondary-nav-utils). Tests pass fixtures. An omitted map is empty,
 * which is today's cookbooks / browse result: null.
 */
export function getActiveSecondaryNavId(
  pathname,
  entry,
  searchParams,
  pathToSidebarMap,
  sidebarToSecondaryNav,
) {
  const map = pathToSidebarMap ?? new Map()
  const table = sidebarToSecondaryNav ?? {}

  // Map old home routes for backwards compatibility
  if (pathname === '/home/saaskit/' || pathname === '/home/saaskit') {
    return 'saaskit-user-management'
  }

  // 1. First check explicit topic from page frontmatter
  if (entry?.data?.topic) {
    const mapping = table[entry.data.topic]
    if (mapping) {
      return resolveNavMapping(mapping, pathname)
    }
  }

  // 2. Fall back to path-based sidebar lookup
  const sidebarId = getSidebarIdForPath(pathname, map)

  if (sidebarId && table[sidebarId]) {
    return resolveNavMapping(table[sidebarId], pathname)
  }

  // 3. Hard-coded fallbacks for pages without a sidebar (e.g. Scalar /apis, product hubs)
  if (pathname.startsWith('/agentkit/apis')) return 'agentkit-api-reference'
  if (pathname.startsWith('/saaskit/apis')) return 'saaskit-apis'
  if (pathname.startsWith('/apis')) return 'saaskit-apis'
  if (pathname.startsWith('/saaskit/sdks')) return 'saaskit-sdks'
  if (pathname === '/sdks' || pathname.startsWith('/sdks/')) return 'saaskit-sdks'
  if (pathname.startsWith('/agentkit/sdks')) return 'agentkit-sdks'

  // Fallback for AgentKit pages not registered in the sidebar map
  // Routes through the 'connect' mapping which has path overrides for all /agentkit/* paths.
  if (pathname.startsWith('/agentkit/') && table['connect']) {
    return resolveNavMapping(table['connect'], pathname)
  }

  return null
}

/**
 * SSR current-tab check. Uses getActiveSecondaryNavId (sidebar table),
 * not href-prefix rematch.
 */
export function isCurrentPage(
  pathname,
  item,
  entry,
  searchParams,
  pathToSidebarMap,
  sidebarToSecondaryNav,
) {
  const activeId = getActiveSecondaryNavId(
    pathname,
    entry,
    searchParams,
    pathToSidebarMap,
    sidebarToSecondaryNav,
  )

  // For dropdown parent items, check if any child is current
  if (item.children && item.children.length > 0) {
    const childIsCurrent = item.children.some((child) => child.id === activeId)
    if (childIsCurrent) return true
  }

  // Hash-only links (dropdown triggers) are never current on their own
  if (isHashOnly(item.href)) {
    return false
  }

  // Check if this item's ID matches the active nav ID
  return activeId === item.id
}

export function getDisplayLabel(
  pathname,
  item,
  entry,
  searchParams,
  pathToSidebarMap,
  sidebarToSecondaryNav,
) {
  if (item.id === 'authenticate') {
    if (item.children && item.children.length > 0) {
      const activeChild = item.children.find((child) =>
        isCurrentPage(
          pathname,
          child,
          entry,
          searchParams,
          pathToSidebarMap,
          sidebarToSecondaryNav,
        ),
      )
      if (!activeChild) return 'Choose product'
      return activeChild.label
    }

    return 'Choose product'
  }

  if (item.children && item.children.length > 0) {
    const activeChild = item.children.find((child) =>
      isCurrentPage(pathname, child, entry, searchParams, pathToSidebarMap, sidebarToSecondaryNav),
    )
    // For right column items (Full-stack Auth shortcuts), always use parent label
    if (activeChild && activeChild.columnGroup === 'right') {
      return item.label
    }
    // For left column items (Modular Auth), use child label
    if (activeChild) return activeChild.label
  }
  return item.label
}

/**
 * Client rematch: longest href prefix.
 *
 * SecondaryNav must call this (or the same prefix rule). Do not replace
 * it with getActiveSecondaryNavId — that would "fix" cookbooks and
 * other SSR/client disagreements.
 *
 * Length compare matches the live loop: candidate uses the slash-stripped
 * href; the current best uses href.split('#')[0] without stripping slashes.
 *
 * @param {string} pathname
 * @param {Array<{ href?: string | null }>} items
 * @returns {{ href: string } | null}
 */
export function matchCurrentByHrefPrefix(pathname, items) {
  let matchingItem = null

  for (const item of items) {
    const href = item.href
    if (!href) continue

    const normalizedPath = pathname.replace(/\/+$/, '')
    const normalizedHref = href.replace(/\/+$/, '').split('#')[0]

    if (normalizedPath.startsWith(normalizedHref) && normalizedHref !== '') {
      if (!matchingItem || normalizedHref.length > (matchingItem.href?.split('#')[0].length || 0)) {
        matchingItem = item
      }
    }
  }

  return matchingItem
}
